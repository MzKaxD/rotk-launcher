import { copyFile, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = process.argv[2];
if (!source) throw new Error("Usage: node scripts/stage-fairplay.mjs <private-build/FairPlay.exe>");
const binary = await readFile(resolve(source));
if (binary.length > 32 * 1024 * 1024 || binary.length < 128 || binary.readUInt16LE(0) !== 0x5a4d) throw new Error("Expected a Windows PE executable.");
const pe = binary.readUInt32LE(0x3c);
if (pe + 24 > binary.length || binary.readUInt32LE(pe) !== 0x4550 || binary.readUInt16LE(pe + 4) !== 0x8664) throw new Error("Expected an x64 PE executable.");
const digest = createHash("sha256").update(binary).digest("hex");
const destination = resolve(root, "resources/fairplay/FairPlay.exe");
await mkdir(dirname(destination), { recursive: true });
await copyFile(resolve(source), destination);
await writeFile(resolve(root, "electron/services/fairplay-release.ts"),
  '// Generated by scripts/stage-fairplay.mjs. Native source is maintained separately.\n'
  + 'export const FAIRPLAY_VERSION = "0.1.0";\n'
  + `export const FAIRPLAY_SHA256 = "${digest}";\n`);
await writeFile(`${destination}.sha256`, `${digest}  FairPlay.exe\n`);
console.log(`Staged FairPlay.exe: ${(await stat(destination)).size} bytes, SHA-256 ${digest}`);
