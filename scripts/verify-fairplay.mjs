import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const release = await readFile(resolve(root, "electron/services/fairplay-release.ts"), "utf8");
const expected = release.match(/FAIRPLAY_SHA256 = "([a-f0-9]{64})"/)?.[1];
if (!expected) throw new Error("FairPlay has not been staged for this release.");
const binary = await readFile(resolve(root, "resources/fairplay/FairPlay.exe"));
if (createHash("sha256").update(binary).digest("hex") !== expected) throw new Error("FairPlay release integrity mismatch.");
console.log("FairPlay release integrity verified.");
